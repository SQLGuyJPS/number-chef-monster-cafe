// Writes docs/ECONOMY_SIM.md (D150): the shop catalog with prices (D148), and simulated play against it
// (engine/economySim.ts). Deterministic: same flags, same file. Flags (all optional):
//   --minutes 60        play minutes per week
//   --session 15-20     minutes per sitting
//   --service 3-4       minutes per 6-order service
//   --between 0.5       minutes of Results and menu between services
//   --shop 1.5          minutes in the shop at the end of a sitting
//   --crate-every 45    monsters served per delivery crate
//   (npm run play:report measures these from a backup, D189)
//   --tiers 20,35,65,120,220   tier 1–5 prices
//   --decor-week 7 --wardrobe-week 12 --staff-week 20   when the later waves reach the device
//   --runs 300          seeded runs per scenario
//   --out docs/ECONOMY_SIM.md   (use --out - to print instead)
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import {
  CRATE_EVERY_MONSTERS,
  CRATE_HOLD_AT_UNBOUGHT,
  CRATE_SIZE,
  LATER_GROUPS,
  M4_ITEMS,
  STARTER_SHELF,
  TIER_PRICE,
  expandCatalog,
  expandPlanned,
  type Tier,
} from '../src/engine/economy';
import { CRATE_QUEUE } from '../src/engine/shop';
import {
  DEFAULT_PROFILE,
  percentile,
  simulate,
  type BuyPolicy,
  type CrateRule,
  type PlayProfile,
  type SimInput,
  type SimResult,
} from '../src/engine/economySim';
import { hashSeed, mulberry32 } from '../src/engine/rng';

const WEEKS_PER_MONTH = 52 / 12;

function flag(name: string): string | undefined {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : undefined;
}
const range = (s: string | undefined, d: readonly [number, number]): [number, number] => {
  if (!s) return [d[0], d[1]];
  const [a, b] = s.split('-').map(Number);
  return [a!, b ?? a!];
};

const profile: PlayProfile = {
  ...DEFAULT_PROFILE,
  minutesPerWeek: Number(flag('minutes') ?? DEFAULT_PROFILE.minutesPerWeek),
  sessionMinutes: range(flag('session'), DEFAULT_PROFILE.sessionMinutes),
  serviceMinutes: range(flag('service'), DEFAULT_PROFILE.serviceMinutes),
  betweenServicesMinutes: Number(flag('between') ?? DEFAULT_PROFILE.betweenServicesMinutes),
  shopMinutes: Number(flag('shop') ?? DEFAULT_PROFILE.shopMinutes),
};
const tierList = (flag('tiers') ?? Object.values(TIER_PRICE).join(',')).split(',').map(Number);
const tiers = {
  1: tierList[0]!,
  2: tierList[1]!,
  3: tierList[2]!,
  4: tierList[3]!,
  5: tierList[4]!,
} as Record<Tier, number>;
const decorWeek = Number(flag('decor-week') ?? 7);
const wardrobeWeek = Number(flag('wardrobe-week') ?? 12);
const staffWeek = Number(flag('staff-week') ?? 20);
const RUNS = Number(flag('runs') ?? 300);
const outFlag = flag('out') ?? fileURLToPath(new URL('../docs/ECONOMY_SIM.md', import.meta.url));

const scaled = (k: number) =>
  Object.fromEntries(
    Object.entries(tiers).map(([t, v]) => [t, Math.round((v * k) / 5) * 5]),
  ) as Record<Tier, number>;
const m4 = (t = tiers) => expandCatalog(M4_ITEMS, t);
const later = (t = tiers) => expandPlanned(LATER_GROUPS, t);
const shelf = new Set(STARTER_SHELF);
const starter = (t = tiers) => m4(t).filter((e) => shelf.has(e.key));
/** The rest of M4 waits in the crate queue from day one (D151), in the game's crate order (D182). */
const m4Wave = (t = tiers) => {
  const byKey = new Map(m4(t).map((e) => [e.key, e]));
  return { id: 'm4', opensWeek: 0, ordered: true, entries: CRATE_QUEUE.map((k) => byKey.get(k)!) };
};
const CRATES: CrateRule = {
  everyMonsters: Number(flag('crate-every') ?? CRATE_EVERY_MONSTERS),
  size: CRATE_SIZE,
  holdAtStock: CRATE_HOLD_AT_UNBOUGHT,
};
const WAVE_WEEKS: Record<string, number> = {
  decor: decorWeek,
  wardrobe: wardrobeWeek,
  staff: staffWeek,
};
const waves = (t = tiers) => {
  const all = later(t);
  return Object.entries(WAVE_WEEKS).map(([id, opensWeek]) => ({
    id,
    opensWeek,
    entries: all.filter((e) => e.wave === id),
  }));
};

function runMany(
  label: string,
  make: () => Omit<SimInput, 'policy'> & { policy?: BuyPolicy },
  policy: BuyPolicy = 'impulse',
): SimResult[] {
  return Array.from({ length: RUNS }, (_, i) =>
    simulate({ policy, ...make() }, mulberry32(hashSeed('economy', label, policy, i))),
  );
}

const n0 = (n: number) => Math.round(n).toLocaleString('en-US');
const fmt = (n: number | null, digits = 1) => (n === null ? 'never' : n.toFixed(digits));
const med = (xs: (number | null)[]) => percentile(xs, 50);
const spread = (xs: (number | null)[], digits = 1) =>
  `${fmt(med(xs), digits)} (${fmt(percentile(xs, 10), digits)}–${fmt(percentile(xs, 90), digits)})`;
const months = (w: number | null) => (w === null ? 'never' : (w / WEEKS_PER_MONTH).toFixed(1));
const sum = (xs: { price: number }[]) => xs.reduce((s, e) => s + e.price, 0);

const lines: string[] = [];
const out = (s = '') => lines.push(s);

// ---- Header and assumptions
out('# Shop economy simulation');
out();
out(
  'Generated by `npm run economy:sim` from `src/engine/economy.ts` (catalog, D148) and `src/engine/economySim.ts`. Later content is planned counts (D149). Each figure is the median of ' +
    RUNS +
    ' seeded runs, with the 10th–90th percentile in brackets.',
);
out();
out('## Assumptions');
out();
out(
  `- Play: ${profile.minutesPerWeek} min a week, in sittings of ${profile.sessionMinutes.join('–')} min; a ${profile.orders}-order service takes ${profile.serviceMinutes.join('–')} min, plus ${profile.betweenServicesMinutes} min of Results and menu between services and ${profile.shopMinutes} min in the shop at the end of a sitting that has something to buy.`,
);
out(
  `- A service starts only with ≥ ${profile.minMinutesToStart} min of the sitting left (and then is finished). Requeues: one in ${Math.round(profile.requeueOne * 100)}% of services, two in ${Math.round(profile.requeueTwo * 100)}%. ${Math.round(profile.partialRate * 100)}% of services are closed early (no tip).`,
);
out(
  '- Earning is SPEC §9 unchanged: 3 coins a monster, +5 tip for a finished service (23 for a plain 6-order service).',
);
out(
  `- Tier prices: ${(Object.keys(tiers) as unknown as Tier[]).map((t) => `T${t} ${tiers[t]}`).join(' · ')}. Every colorway costs the item's price (D177); colorways of a free default cost T1.`,
);
out(
  '- Spending habits: **impulse** buys something random she can afford, up to 2 a sitting; **cheapest** buys the cheapest things first, as many as she can; **saver** picks a wish and buys it as soon as she can (the wish-item milestone).',
);
out();

// ---- Earnings
const base = runMany('earn', () => ({
  profile,
  maxBuysPerVisit: 2,
  starting: m4(),
  waves: [],
  weeks: 20,
}));
const perWeek = (f: (w: SimResult['weeks'][number]) => number) =>
  base.map((r) => r.weeks.slice(0, 20).reduce((s, w) => s + f(w), 0) / 20);
const coinsWeek = med(perWeek((w) => w.coins))!;
const monstersWeek = med(perWeek((w) => w.monsters))!;
out('## What she earns');
out();
out('| Per week | Median (10th–90th) |');
out('|---|---|');
out(`| Sittings | ${spread(perWeek((w) => w.sessions))} |`);
out(`| Services | ${spread(perWeek((w) => w.services))} |`);
out(
  `| Monsters served | ${spread(
    perWeek((w) => w.monsters),
    0,
  )} |`,
);
out(
  `| Coins | ${spread(
    perWeek((w) => w.coins),
    0,
  )} |`,
);
out();
out(
  `So about **${Math.round(coinsWeek)} coins a week** and **${Math.round(monstersWeek)} monsters a week**, about ${n0(coinsWeek * WEEKS_PER_MONTH)} coins a month. Two months of play is about ${n0(coinsWeek * 2 * WEEKS_PER_MONTH)} coins; another 6–9 months is about ${n0(coinsWeek * 6 * WEEKS_PER_MONTH)}–${n0(coinsWeek * 9 * WEEKS_PER_MONTH)}.`,
);
out();

// ---- Tiers in play time
out('## What a tier costs in play');
out();
out('| Tier | Price | Services | Sittings | Weeks at this pace |');
out('|---|---|---|---|---|');
const coinsService = coinsWeek / med(perWeek((w) => w.services))!;
const coinsSitting = coinsWeek / med(perWeek((w) => w.sessions))!;
for (const t of [1, 2, 3, 4, 5] as Tier[]) {
  out(
    `| T${t} | ${tiers[t]} | ${(tiers[t] / coinsService).toFixed(1)} | ${(tiers[t] / coinsSitting).toFixed(1)} | ${(tiers[t] / coinsWeek).toFixed(2)} |`,
  );
}
out();

// ---- Catalog
const entries = m4();
const paid = entries.filter((e) => e.price > 0);
out('## M4 catalog (SPEC §10)');
out();
out(
  `${M4_ITEMS.length} items, ${paid.length} paid entries (items × colorways), total **${sum(paid).toLocaleString('en-US')} coins** (before D148: 30 items, 1,340).`,
);
out();
out('| Slot | Item | Tier | Colorways (price) |');
out('|---|---|---|---|');
for (const def of M4_ITEMS) {
  const mine = entries.filter((e) => e.item === def.id && e.slot === def.slot);
  const cw = mine
    .map(
      (e) =>
        `${e.colorway === 'classic' ? 'Classic' : e.colorway[0]!.toUpperCase() + e.colorway.slice(1)} ${e.price === 0 ? 'free' : e.price}`,
    )
    .join(', ');
  out(
    `| ${def.slot} | ${def.name}${def.free ? ' (default)' : ''} | ${def.free ? '—' : `T${def.tier}`} | ${cw} |`,
  );
}
out();
out('| Slot | Paid entries | Coins |');
out('|---|---|---|');
for (const slot of [...new Set(entries.map((e) => e.slot))]) {
  const s = paid.filter((e) => e.slot === slot);
  out(`| ${slot} | ${s.length} | ${sum(s)} |`);
}
out();
const tierCounts = ([1, 2, 3, 4, 5] as Tier[]).map(
  (t) => `T${t}: ${paid.filter((e) => e.tier === t).length}`,
);
out(`Entries per tier (colorways counted with their item's tier): ${tierCounts.join(' · ')}.`);
out();

// ---- M4 alone
out('## M4 shop alone (no later content)');
out();
out(
  `M4 opens with a starter shelf of ${starter().length} entries (${sum(starter())} coins); the other ${m4Wave().entries.length} arrive in crates (D151). The all-on-day-one rows are for comparison.`,
);
out();
out(
  '| Setup | Habit | First purchase: end of sitting / after services | Bought out (weeks) | Bought out (months) | Mean unbought items on the shelf | Sittings ending with a purchase | Longest dry spell (sittings, 90th pct) |',
);
out('|---|---|---|---|---|---|---|---|');
const setups: [string, () => Omit<SimInput, 'policy' | 'profile' | 'maxBuysPerVisit' | 'weeks'>][] =
  [
    ['Starter shelf + crates', () => ({ starting: starter(), waves: [m4Wave()], crates: CRATES })],
    ['All on day one', () => ({ starting: m4(), waves: [] })],
  ];
for (const [setup, make] of setups)
  for (const policy of ['impulse', 'cheapest', 'saver'] as BuyPolicy[]) {
    const rs = runMany(
      `m4-${setup}`,
      () => ({ profile, maxBuysPerVisit: 2, weeks: 60, ...make() }),
      policy,
    );
    const bo = rs.map((r) => r.allBoughtOutWeek);
    const share = rs.map((r) =>
      r.activeSessions > 0 ? (100 * r.purchaseSessions) / r.activeSessions : 0,
    );
    out(
      `| ${setup} | ${policy} | ${fmt(med(rs.map((r) => r.firstPurchaseSession)), 0)} / ${fmt(med(rs.map((r) => r.firstPurchaseServices)), 0)} | ${spread(bo)} | ${months(med(bo))} | ${fmt(med(rs.map((r) => r.meanStock)))} | ${fmt(med(share), 0)}% | ${fmt(
        percentile(
          rs.map((r) => r.longestDry),
          90,
        ),
        0,
      )} |`,
    );
  }
out();

// ---- Sensitivity
out('### How the buy-out moves (impulse habit, starter shelf + crates)');
out();
out('| Change | Catalog coins | Bought out (weeks) | Months |');
out('|---|---|---|---|');
const sens: [string, PlayProfile, Record<Tier, number>][] = [
  ['Prices × 0.8', profile, scaled(0.8)],
  ['Prices as set (D148, D191)', profile, tiers],
  ['Prices × 1.2', profile, scaled(1.2)],
  ['45 min a week', { ...profile, minutesPerWeek: 45 }, tiers],
  ['90 min a week', { ...profile, minutesPerWeek: 90 }, tiers],
  ['Services take 4–5 min', { ...profile, serviceMinutes: [4, 5] }, tiers],
  [
    '8 orders a service',
    {
      ...profile,
      orders: 8,
      serviceMinutes: [(profile.serviceMinutes[0] * 8) / 6, (profile.serviceMinutes[1] * 8) / 6],
    },
    tiers,
  ],
];
for (const [label, prof, t] of sens) {
  const rs = runMany(`sens-${label}`, () => ({
    profile: prof,
    maxBuysPerVisit: 2,
    starting: starter(t),
    waves: [m4Wave(t)],
    crates: CRATES,
    weeks: 80,
  }));
  const bo = rs.map((r) => r.allBoughtOutWeek);
  out(
    `| ${label} | ${sum(m4(t).filter((e) => e.price > 0)).toLocaleString('en-US')} | ${spread(bo)} | ${months(med(bo))} |`,
  );
}
out();

// ---- Later content
const lat = later();
out('## Later content (planned counts, not designed yet)');
out();
out('| Group | Wave | Count | Price each | Coins |');
out('|---|---|---|---|---|');
for (const g of LATER_GROUPS) {
  const es = lat.filter((e) => e.name === g.label);
  out(
    `| ${g.label} | ${g.wave} | ${g.count} | ${es[0]?.price ?? 0} | ${sum(es).toLocaleString('en-US')} |`,
  );
}
const decorCoins = sum(lat.filter((e) => e.wave === 'decor'));
const wardCoins = sum(lat.filter((e) => e.wave === 'wardrobe'));
const staffCoins = sum(lat.filter((e) => e.wave === 'staff'));
out(`| **Total** | | ${lat.length} | | **${sum(lat).toLocaleString('en-US')}** |`);
out();
out(
  `Decor wave ${decorCoins.toLocaleString('en-US')} coins (≈ ${(decorCoins / coinsWeek).toFixed(1)} weeks of earning); wardrobe wave ${wardCoins.toLocaleString('en-US')} (≈ ${(wardCoins / coinsWeek).toFixed(1)} weeks); staff wave (M18, D157) ${staffCoins.toLocaleString('en-US')} (≈ ${(staffCoins / coinsWeek).toFixed(1)} weeks). Together ≈ ${months(sum(lat) / coinsWeek)} months of earning; the target is 6–9.`,
);
out();

// ---- Roadmap with crates
out(
  `## Whole roadmap with crates (M4 starter shelf and M4 crates from day one, decor wave in week ${decorWeek}, wardrobe wave in week ${wardrobeWeek}, staff wave in week ${staffWeek})`,
);
out();
out(
  'Shop-stock, waiting and dry-spell columns count from the decor wave on; a later wave joins the crate queue behind whatever M4 items are still waiting. A crate is counted in monsters served (owner, 2026-11-21), so a short or 4-order service still moves it on. The first crate of a wave comes with the update; the rest follow every N monsters. Target: everything owned about 8–11 months after M4 (2 months of M4 + 6–9 more).',
);
out();
out(
  '| Crate rule | Crates for all later items | Everything owned (months) | Mean unowned items in the shop | Sittings with nothing to buy (waiting) | Longest dry spell (90th pct) |',
);
out('|---|---|---|---|---|---|');
const rules: CrateRule[] = [
  { everyMonsters: 30, size: 1 },
  { everyMonsters: 45, size: 2 },
  { everyMonsters: 60, size: 2 },
  { everyMonsters: 60, size: 3 },
  { everyMonsters: 90, size: 3 },
  { everyMonsters: 90, size: 4 },
  { everyMonsters: 120, size: 4 },
  { everyMonsters: 30, size: 2, holdAtStock: 6 },
  { everyMonsters: 40, size: 2, holdAtStock: 6 },
  { everyMonsters: 45, size: 2, holdAtStock: 6 },
  { everyMonsters: 45, size: 3, holdAtStock: 6 },
];
for (const crates of rules) {
  const rs = runMany(`crates-${crates.everyMonsters}-${crates.size}`, () => ({
    profile,
    maxBuysPerVisit: 2,
    starting: starter(),
    waves: [m4Wave(), ...waves()],
    crates,
    weeks: 120,
    measureFromWeek: decorWeek,
  }));
  const done = rs.map((r) => r.allBoughtOutWeek);
  const empty = rs.map((r) => (100 * r.emptyShopSessions) / Math.max(1, r.activeSessions));
  out(
    `| ${crates.size} every ${crates.everyMonsters} monsters${crates.holdAtStock ? `, held while ${crates.holdAtStock}+ unbought` : ''}${crates.everyMonsters === CRATE_EVERY_MONSTERS && crates.size === 2 && crates.holdAtStock ? ' **(chosen, D151, D190)**' : ''} (≈ every ${((crates.everyMonsters / monstersWeek) * 7).toFixed(1)} days) | ${Object.keys(WAVE_WEEKS).reduce((n, id) => n + Math.ceil(lat.filter((e) => e.wave === id).length / crates.size), 0)} | ${months(med(done))} (${months(percentile(done, 10))}–${months(percentile(done, 90))}) | ${fmt(med(rs.map((r) => r.meanStock)))} | ${fmt(med(empty), 0)}% | ${fmt(
      percentile(
        rs.map((r) => r.longestDry),
        90,
      ),
      0,
    )} |`,
  );
}
{
  const rs = runMany('no-crates', () => ({
    profile,
    maxBuysPerVisit: 2,
    starting: m4(),
    waves: waves(),
    weeks: 120,
    measureFromWeek: decorWeek,
  }));
  const done = rs.map((r) => r.allBoughtOutWeek);
  const empty = rs.map((r) => (100 * r.emptyShopSessions) / Math.max(1, r.activeSessions));
  out(
    `| No crates (each wave all at once) | — | ${months(med(done))} (${months(percentile(done, 10))}–${months(percentile(done, 90))}) | ${fmt(med(rs.map((r) => r.meanStock)))} | ${fmt(med(empty), 0)}% | ${fmt(
      percentile(
        rs.map((r) => r.longestDry),
        90,
      ),
      0,
    )} |`,
  );
}
out();

const text = lines.join('\n') + '\n';
if (outFlag === '-') process.stdout.write(text);
else {
  writeFileSync(outFlag, text);
  console.log(`Wrote ${outFlag}`);
}
