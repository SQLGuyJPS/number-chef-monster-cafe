// Writes docs/CONTENT_REVIEW.md (SPEC §13.3): per skill the pool size, 12 deterministic sample
// problems (ticket, spoken line, tray at S3 and S1) and one demo per strategy, plus the monster
// roster lines. The owner skims it at M2 and M5. Deterministic: same code, same file.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { BUILT_SKILLS, isAddition, pool } from '../src/engine/generators';
import { buildDemo, type TrayOp } from '../src/engine/demos';
import { phrase } from '../src/engine/phrases';
import { hashSeed, mulberry32 } from '../src/engine/rng';
import { toTrayTask } from '../src/engine/tray';
import type { Problem } from '../src/engine/types';
import { ticketLine } from '../src/game/service/controller';
import { MONSTER_SPECS } from '../src/art/monsters/specs';

const out = fileURLToPath(new URL('../docs/CONTENT_REVIEW.md', import.meta.url));
const SAMPLES = 12;

const ticket = (p: Problem) => p.display.join(' ');
const spoken = (p: Problem) => ticketLine({ problem: p, food: 'cookie', stage: 3, monster: 'blobbo' });
const tray = (p: Problem, stage: 3 | 1) => {
  const t = toTrayTask(p, stage);
  const mode = t.mode === 'remove' ? 'take away' : 'add';
  return `${t.prefill.frameCells} → ${t.expected.cells} (${mode}${t.takenAwayRow ? ', taken-away row' : ''})`;
};
const opText = (o: TrayOp) =>
  o.op === 'glow' ? `glow ${o.cells.map((c) => c + 1).join(',')}` : o.op === 'none' ? '' : `${o.op} one`;

/** Deterministic sample: a seeded shuffle of the pool, first 12, shown in difficulty order. */
function sample(items: Problem[], seed: string): Problem[] {
  const rng = mulberry32(hashSeed(seed));
  const a = items.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = rng.int(0, i);
    [a[i], a[j]] = [a[j]!, a[i]!];
  }
  return a.slice(0, SAMPLES).sort((x, y) => x.difficulty - y.difficulty || ticket(x).localeCompare(ticket(y)));
}

const lines: string[] = [
  '# Content review',
  '',
  'Generated by `npm run content:table` (SPEC §13.3). Do not edit by hand.',
  '',
  'Spoken lines use cookies as the example food. Tray: cells at the start → cells when right, at S3',
  '(prefilled) and S1 (build only the unknown).',
  '',
];

for (const skill of BUILT_SKILLS) {
  const items = pool(skill);
  const add = items.filter(isAddition).length;
  lines.push(`## ${skill}`, '', `Pool: ${items.length} presentations (${add} addition, ${items.length - add} subtraction), ${new Set(items.map((p) => p.factKey)).size} facts.`, '');
  lines.push('| Ticket | Spoken | Strategy | Difficulty | Tray S3 | Tray S1 |', '|---|---|---|---|---|---|');
  for (const p of sample(items, `content:${skill}`)) {
    lines.push(`| \`${ticket(p)}\` | ${spoken(p)} | ${p.strategy} | ${p.difficulty} | ${tray(p, 3)} | ${tray(p, 1)} |`);
  }
  lines.push('', `### ${skill} demos (one per strategy and form)`, '');
  const seen = new Set<string>();
  for (const p of items) {
    const kind = `${p.strategy} · ${p.form}`;
    if (seen.has(kind)) continue;
    seen.add(kind);
    lines.push(`**\`${ticket(p)}\`** (${kind})`, '');
    for (const st of buildDemo(p)) {
      const op = opText(st.trayOp);
      lines.push(`1. ${phrase(st.narrationKey, st.params)}${op ? ` — _${op}_` : ''}`);
    }
    lines.push('');
  }
}

lines.push('## Monsters', '', '| Monster | Favourites | Voice (pitch, rate) | Hello | Thanks | Reaction |', '|---|---|---|---|---|---|');
for (const m of MONSTER_SPECS) {
  lines.push(
    `| ${m.name} | ${m.favorites.join(', ')} | ${m.voice.pitch}, ${m.voice.rate} | ${m.lines.arrive.join(' / ')} | ${m.lines.thanks.join(' / ')} | ${m.reactions.join(', ')} |`,
  );
}
lines.push('');

writeFileSync(out, lines.join('\n'));
console.log(`content:table: wrote docs/CONTENT_REVIEW.md (${BUILT_SKILLS.join(', ')}; ${MONSTER_SPECS.length} monsters)`);
