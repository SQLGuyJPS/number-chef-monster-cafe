// `npm run audio:todo [-- --spike]` (SPEC §8.4, D140c, D144): writes the recording script
// (docs/VOICE_SCRIPT.md, or docs/VOICE_SPIKE.md with --spike) and lists the clips the manifest lacks.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { VOICE_IDS } from '../src/engine/clips';
import { emptyManifest, missingClips, parseManifest } from '../src/engine/voiceManifest';
import {
  fullScript,
  renderScript,
  scriptItemCount,
  spikeScript,
  voiceInventory,
  type ScriptSection,
} from '../src/engine/voiceScript';
import { MONSTER_LINES, TICKETS } from './voice-data';

const repo = fileURLToPath(new URL('../', import.meta.url));
const spike = process.argv.includes('--spike');

/** About 1.7 s per carrier sentence plus a breath: the estimate printed on the script. */
const SECONDS_PER_ITEM = 4;

const HOW = (file: string, folder: string) => [
  'Generated by `npm run audio:todo' +
    (spike ? ' -- --spike' : '') +
    '`; do not edit by hand (the build reads the numbers back).',
  '',
  '**How to record** (D140c):',
  '',
  '1. Quiet room, the mic at a steady distance, an even, friendly pace. Read each line in full, as the game says it; leave a short breath between lines. Several takes are fine.',
  `2. In Audacity select only the **bold** words of the take you keep and press Ctrl+B; type the line's number as the label. One label per number.`,
  `3. File → Export Audio: WAV, mono (any sample rate; 48 kHz / 24-bit preferred). File → Export → Export Labels: the same name as the WAV, \`.txt\`. Both into \`${folder}\`.`,
  `4. Run \`npm run audio:build -- --src ${folder}\`. It reports missing, extra and duplicate numbers before it writes anything.`,
  '',
  `Script: \`${file}\`.`,
];

function render(sections: ScriptSection[]): { file: string; md: string } {
  const file = spike ? 'docs/VOICE_SPIKE.md' : 'docs/VOICE_SCRIPT.md';
  const folder = spike ? 'voice-masters/spike' : 'voice-masters/full';
  const count = scriptItemCount(sections);
  const minutes = Math.ceil((count * SECONDS_PER_ITEM) / 60);
  const title = spike
    ? 'Voice spike: listening-test recording (M13 step 2)'
    : 'Voice script: Little Menu A1–A3, numbers 0–20';
  const intro = [...HOW(file, folder), '', `${count} lines, about ${minutes} minutes of reading.`];
  return { file, md: renderScript(title, intro, sections) };
}

const sections = spike ? spikeScript() : fullScript(MONSTER_LINES, TICKETS);
const { file, md } = render(sections);
writeFileSync(join(repo, file), md);
console.log(`audio:todo: wrote ${file} (${scriptItemCount(sections)} lines)`);

const manifestPath = join(repo, 'public/audio/manifest.json');
const manifest = existsSync(manifestPath)
  ? parseManifest(JSON.parse(readFileSync(manifestPath, 'utf8')))
  : emptyManifest();
if (!manifest) {
  console.error('audio:todo: public/audio/manifest.json is not a valid manifest');
  process.exit(1);
}

// What each voice still lacks: the spike checks its own clips in every voice, the full script the inventory.
const spikeClips = sections.flatMap((s) => s.items.map((i) => i.clip));
const want: Map<string, readonly string[]> = spike
  ? new Map(VOICE_IDS.map((v) => [v, spikeClips]))
  : new Map([...voiceInventory(MONSTER_LINES, TICKETS)].map(([v, s]) => [v, [...s]]));
let missingTotal = 0;
for (const [voice, clips] of want) {
  const miss = missingClips(manifest, voice, clips);
  missingTotal += miss.length;
  const shown = miss.slice(0, 8).join(', ') + (miss.length > 8 ? `, … (+${miss.length - 8})` : '');
  console.log(
    `  ${voice.padEnd(10)} ${miss.length ? `${miss.length} of ${clips.length} missing: ${shown}` : `all ${clips.length} recorded`}`,
  );
}
console.log(
  missingTotal ? `audio:todo: ${missingTotal} clips missing` : 'audio:todo: nothing missing',
);
