import { mkdirSync, writeFileSync } from 'node:fs';
import { test } from '@playwright/test';
import { openService, probe, serveCorrect, waitPhase } from './service';

// 4× CPU throttle frame report (SPEC §14 M2; a report, not a gate). Chromium iPad Pro 11 only:
//   npx cross-env NCMC_PERF=1 playwright test perf --project=chromium-ipad-pro-11
test.skip(!process.env.NCMC_PERF, 'set NCMC_PERF=1 to write docs/perf/M2-throttle.md');

test('4× CPU throttle: frame times through three orders (arrive, build, serve, eat, coins)', async ({
  page,
}, info) => {
  test.skip(info.project.name !== 'chromium-ipad-pro-11', 'CDP throttling is Chromium-only');
  test.setTimeout(120_000);
  await openService(page, { skill: 'A2', stage: 3, ops: 'add', seed: 5, timeScale: 1 });
  const cdp = await page.context().newCDPSession(page);
  await cdp.send('Emulation.setCPUThrottlingRate', { rate: 4 });
  await page.evaluate(() => {
    const w = window as unknown as { __frames: number[]; __long: number[] };
    w.__frames = [];
    w.__long = [];
    // Main-thread tasks over 50 ms (headless frame pacing can hide them from rAF deltas).
    new PerformanceObserver((l) => l.getEntries().forEach((e) => w.__long.push(e.duration))).observe({
      type: 'longtask',
      buffered: false,
    });
    let last = performance.now();
    const loop = (t: number) => {
      w.__frames.push(t - last);
      last = t;
      requestAnimationFrame(loop);
    };
    requestAnimationFrame(loop);
  });
  const t0 = Date.now();
  for (let i = 0; i < 3; i++) {
    await waitPhase(page, 'building');
    await serveCorrect(page);
    await page.waitForFunction((n) => window.__ncmc.service()!.index === n, i + 1, { timeout: 20_000 });
  }
  const seconds = (Date.now() - t0) / 1000;
  const frames = await page.evaluate(() => (window as unknown as { __frames: number[] }).__frames.slice(1));
  const long = await page.evaluate(() => (window as unknown as { __long: number[] }).__long.slice());
  await cdp.send('Emulation.setCPUThrottlingRate', { rate: 1 });
  const sorted = frames.slice().sort((a, b) => a - b);
  const q = (p: number) => sorted[Math.min(sorted.length - 1, Math.floor(p * sorted.length))]!;
  const over = (ms: number) => frames.filter((f) => f > ms).length;
  const pct = (n: number) => `${((100 * n) / frames.length).toFixed(1)}%`;
  const fmt = (n: number) => n.toFixed(1);
  const report = [
    '# M2 — 4× CPU throttle frame report',
    '',
    'Generated by `tests/e2e/perf.spec.ts` (SPEC §14 M2; a report, not a gate). Chromium, iPad Pro 11',
    'landscape viewport, CPU throttled 4× with DevTools emulation, real-time service (no fast-forward).',
    'Covers three orders: monster arrival, building by tap, serve, the eat sequence with food',
    'flights, chewing, the reaction and coin flights, and the next arrival.',
    'A desktop CPU slowed 4× is only a rough stand-in for the iPad; judge smoothness on the device.',
    '',
    `Generated ${new Date().toISOString().slice(0, 10)} · ${frames.length} frames over ${fmt(seconds)} s · ${(await probe(page)).index} orders served`,
    '',
    '| Measure | Value |',
    '|---|---|',
    `| Average fps | ${fmt(frames.length / frames.reduce((a, b) => a + b, 0) * 1000)} |`,
    `| Median frame | ${fmt(q(0.5))} ms |`,
    `| 95th percentile | ${fmt(q(0.95))} ms |`,
    `| 99th percentile | ${fmt(q(0.99))} ms |`,
    `| Longest frame | ${fmt(sorted.at(-1)!)} ms |`,
    `| Frames over 33 ms (below 30 fps) | ${over(33)} (${pct(over(33))}) |`,
    `| Frames over 50 ms | ${over(50)} (${pct(over(50))}) |`,
    `| Frames over 100 ms | ${over(100)} (${pct(over(100))}) |`,
    `| Main-thread long tasks (> 50 ms) | ${long.length}${long.length ? `, longest ${fmt(Math.max(...long))} ms, total ${fmt(long.reduce((a, b) => a + b, 0))} ms` : ''} |`,
    '',
    'Headless Chromium paces frames itself, so frame times can look perfect even when the main',
    'thread is busy; the long-task row is the better signal of jank under load.',
    '',
  ].join('\n');
  mkdirSync('docs/perf', { recursive: true });
  writeFileSync('docs/perf/M2-throttle.md', report);
  console.log(report);
});
