import { mkdirSync, writeFileSync } from 'node:fs';
import { expect, test } from '@playwright/test';
import { MOCK_FRAMES } from '../../src/app/mock/frames';

// M1 step 1 (D36): static layout mock screenshots into docs/screens/M1/mock/, plus annotated copies
// at each size with every tap target measured in CSS px. Runs only when asked:
//   npx cross-env NCMC_MOCK=1 playwright test layout-mock --project=chromium-ipad-pro-11
test.skip(!process.env.NCMC_MOCK, 'set NCMC_MOCK=1 to capture the M1 layout mock');

const SIZES = [
  { width: 1194, height: 834 },
  { width: 844, height: 390 },
];
const MIN = { cell: 44, button: 56 };

interface Measured {
  frame: string;
  size: string;
  kind: string;
  id: string;
  w: number;
  h: number;
  ok: boolean;
}

test('layout mock screenshots', async ({ page }) => {
  test.setTimeout(120_000);
  const dir = 'docs/screens/M1/mock';
  mkdirSync(dir, { recursive: true });
  const rows: Measured[] = [];

  for (const vp of SIZES) {
    await page.setViewportSize(vp);
    const tag = `${vp.width}x${vp.height}`;
    for (const frame of MOCK_FRAMES) {
      await page.goto(`./?mock=${frame}&rotate=off`);
      await expect(page.getByTestId('layout-mock')).toBeVisible();
      await page.evaluate(() => document.fonts.ready);
      // Freeze pulses so screenshots are stable.
      await page.addStyleTag({ content: '*{animation:none!important}' });
      await page.screenshot({ path: `${dir}/${frame}-${tag}.png` });

      const found = await page.evaluate((min) => {
        const out: { kind: string; id: string; w: number; h: number; ok: boolean }[] = [];
        const layer = document.createElement('div');
        layer.style.cssText = 'position:fixed;inset:0;pointer-events:none;z-index:99999';
        document.body.appendChild(layer);
        let cellIndex = 0;
        document.querySelectorAll<HTMLElement>('[data-tap]').forEach((el) => {
          const kind = el.dataset.tap ?? 'button';
          const r = el.getBoundingClientRect();
          const need = kind === 'cell' ? min.cell : min.button;
          const ok = Math.min(r.width, r.height) >= need - 0.01;
          const id = el.dataset.testid ?? `${kind}${kind === 'cell' ? ++cellIndex : ''}`;
          out.push({ kind, id, w: r.width, h: r.height, ok });
          const box = document.createElement('div');
          const colour = ok ? '#0a8f3c' : '#d11';
          box.style.cssText = `position:fixed;left:${r.left}px;top:${r.top}px;width:${r.width}px;height:${r.height}px;outline:2px solid ${colour};box-sizing:border-box`;
          layer.appendChild(box);
          // Label buttons and only the first cell of each frame, to keep the picture readable.
          const firstCell = kind === 'cell' && el.parentElement?.firstElementChild === el;
          if (kind !== 'cell' || firstCell) {
            const label = document.createElement('div');
            label.textContent = `${r.width.toFixed(1)}×${r.height.toFixed(1)}`;
            label.style.cssText = `position:fixed;left:${r.left}px;top:${r.top}px;font:700 11px/1.2 system-ui,sans-serif;color:#fff;background:${colour};padding:1px 3px;border-radius:3px;white-space:nowrap`;
            layer.appendChild(label);
          }
        });
        const legend = document.createElement('div');
        legend.textContent = `CSS px at ${innerWidth}×${innerHeight} · min cell ${min.cell}, button ${min.button} · green = meets minimum`;
        legend.style.cssText =
          'position:fixed;left:50%;top:4px;transform:translateX(-50%);font:700 12px/1.3 system-ui,sans-serif;color:#fff;background:rgba(0,0,0,.7);padding:3px 6px;border-radius:4px';
        layer.appendChild(legend);
        return out;
      }, MIN);
      await page.screenshot({ path: `${dir}/${frame}-${tag}-annotated.png` });
      for (const f of found) rows.push({ frame, size: tag, ...f });
    }
  }

  // Summary table: smallest target of each kind per frame and size.
  const lines = [
    '# M1 layout mock: tap-target sizes (generated by tests/e2e/layout-mock.spec.ts)',
    '',
    `Minimums (SPEC §2.2): tray cells ≥ ${MIN.cell} CSS px, buttons ≥ ${MIN.button} CSS px, measured at 844×390.`,
    '',
    '| Frame | Viewport | Target | CSS px (w × h) | OK |',
    '|---|---|---|---|---|',
  ];
  const seen = new Set<string>();
  for (const r of rows) {
    const key = `${r.frame}|${r.size}|${r.kind === 'cell' ? 'cell' : r.id}`;
    if (seen.has(key)) continue;
    seen.add(key);
    const id = r.kind === 'cell' ? 'tray cell' : r.id;
    lines.push(`| ${r.frame} | ${r.size} | ${id} | ${r.w.toFixed(1)} × ${r.h.toFixed(1)} | ${r.ok ? 'yes' : '**NO**'} |`);
  }
  writeFileSync('docs/screens/M1/mock/tap-sizes.md', lines.join('\n') + '\n');

  const small = rows.filter((r) => r.size === '844x390' && !r.ok);
  expect(small, 'every target meets the 844×390 minimum').toEqual([]);
});
